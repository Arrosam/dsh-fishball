  // Rows 10a–10j: out of an unset value (Q5 = B). The unset is the user's own edit of their
  // credential store; `refresh()` is the credential-change sync that follows it. An unset is a
  // change of the entry's value that neither disables nor deletes it, so of K1's three
  // RevocationKind words it is `value-changed` (design §5.3: "changing or unsetting ... revokes").

  /** The connector's own `credentials.set` calls for `ref` so far. */
  const setsFor = (world, ref) => world.writes.filter((w) => w.op === 'set' && w.ref === ref).length
  /**
   * Q5 = B: `ref`'s entry is `token-unconfigured`, and over the quiet period nothing appears
   * under `ref` and the connector makes no further `credentials.set` for it than `setsBefore`.
   * With `setsBefore` undefined only the store is watched: on an unwritable store a refused
   * attempt writes nothing (the same allowance AUTH-EP-04 row 6 makes).
   */
  async function assertStaysUnconfigured(world, ref, setsBefore, why) {
    await untilStatus(world, ref, ENTRY_STATUS.tokenUnconfigured)
    const generated = async () => (setsBefore !== undefined && setsFor(world, ref) > setsBefore) || (await world.resolve(ref)) !== undefined
    assert.ok(await staysFalse(generated), `a value was generated ${why} (${Q5}: only a settings save generates)`)
    assert.equal(requireEntry(world, ref).status, ENTRY_STATUS.tokenUnconfigured)
  }
  /**
   * A Ready entry whose generated value the user then removed from the store, then synced;
   * `sets` counts the connector's `credentials.set` calls before the unset.
   */
  async function unsetEntry(t) {
    const ready = await readyEntry(t)
    const sets = setsFor(ready.world, A.ref)
    await ready.world.userUnsets(A.ref)
    await ready.world.registry.refresh()
    return { ...ready, sets }
  }
  /** After a settings save: a fresh generated value under `ref`, stored by the connector, `ok`, authenticating. */
  async function assertGeneratedOnSave(world, ref, old) {
    const value = await generatedValue(world, ref)
    assertGeneratedShape(value)
    assert.notEqual(value, old, 'the removed value came back')
    assert.ok(world.writes.some((w) => w.op === 'set' && w.ref === ref && w.value === value), 'the value was not stored with credentials.set')
    await untilStatus(world, ref, ENTRY_STATUS.ok)
    assertMatches(world, ref, value)
    assert.equal(requireEntry(world, ref).generated, true)
    return value
  }

